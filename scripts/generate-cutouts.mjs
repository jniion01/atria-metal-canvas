function bridgeTo(island,root,width){
 let best=Infinity,A,B;
 for(const a of island[0])for(const ring of root)for(let j=1;j<ring.length;j++){
  const b=ring[j-1],c=ring[j],dx=c[0]-b[0],dy=c[1]-b[1],l=dx*dx+dy*dy;if(l<1e-12)continue;
  const f=Math.max(0,Math.min(1,((a[0]-b[0])*dx+(a[1]-b[1])*dy)/l)),q=[b[0]+dx*f,b[1]+dy*f],d=(a[0]-q[0])**2+(a[1]-q[1])**2;
  if(d<best){best=d;A=a;B=q}
 }
 const len=Math.sqrt(best),dx=(B[0]-A[0])/len,dy=(B[1]-A[1])/len,half=width/2;
 const a=[A[0]-dx*width,A[1]-dy*width],b=[B[0]+dx*width,B[1]+dy*width];
 return [[[a[0]-dy*half,a[1]+dx*half],[b[0]-dy*half,b[1]+dx*half],[b[0]+dy*half,b[1]-dx*half],[a[0]+dy*half,a[1]-dx*half],[a[0]-dy*half,a[1]+dx*half]]];
}
