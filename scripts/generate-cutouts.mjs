 let metal=pc.difference(rect(0,0,300,420),cutouts),bridges=0;
 while(metal.length>1&&bridges<80){
  metal.sort((a,b)=>area(b[0])-area(a[0]));const before=metal.length;
  metal=pc.union(metal,bridgeTo(metal[1],metal[0],3));bridges++;
  if(metal.length>=before)throw new Error('Bridge did not join island: '+pattern.id);
 }
